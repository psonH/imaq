const dicts: Record<Lang, Partial<Record<Key, string>>> = { en, fr, iu }

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  // Singular form: a key ending in _one is used when {n} is 1.
  const one = (vars?.n === 1 ? `${key}_one` : null) as Key | null
  let s = (one && (dicts[lang][one] ?? en[one])) || dicts[lang][key] || en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

/** True when the string for this key is still the English fallback. */
export function isFallback(lang: Lang, key: Key) {
  return lang !== 'en' && dicts[lang][key] === undefined
}

